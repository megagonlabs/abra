// @ts-check
/**
 * Codegen pipeline: one JSON-Schema source -> JS `.d.ts` + Pydantic v2 mirror.
 * Output is committed; CI runs `pnpm gen:check` (re-run + git diff) to prevent drift.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileFromFile } from 'json-schema-to-typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const schema = join(root, 'packages/abra-spec/schema/wire.schema.json');
const tsOut = join(root, 'packages/abra-spec/gen/index.d.ts');
const pyOut = join(root, 'adapters/common/spec.py');

// 1) JS / JSDoc types
mkdirSync(dirname(tsOut), { recursive: true });
const ts = await compileFromFile(schema, {
  additionalProperties: false,
  bannerComment:
    '/* GENERATED by `pnpm gen` from packages/abra-spec/schema — do not edit by hand. */',
  style: { singleQuote: true },
});
writeFileSync(tsOut, ts);
console.log('wrote', tsOut);

// 2) Pydantic v2 mirror (camelCase wire -> snake_case Python via aliases)
const venvBin = join(root, '.venv/bin/datamodel-codegen');
const bin = existsSync(venvBin) ? venvBin : 'datamodel-codegen';
const args = [
  '--input',
  schema,
  '--input-file-type',
  'jsonschema',
  '--output',
  pyOut,
  '--output-model-type',
  'pydantic_v2.BaseModel',
  // Use the built-in formatter (not black/isort) so the committed mirror is
  // byte-stable across environments — black/isort versions float and would
  // otherwise break the CI gen-is-clean check.
  '--formatters',
  'builtin',
  '--use-annotated',
  '--use-title-as-name',
  '--snake-case-field',
  '--allow-population-by-field-name',
  '--target-python-version',
  '3.11',
  '--disable-timestamp',
  '--custom-file-header',
  '# GENERATED by `pnpm gen` from packages/abra-spec/schema — do not edit by hand.',
];
const r = spawnSync(bin, args, { stdio: 'inherit' });
if (r.status !== 0) {
  console.error(`datamodel-codegen exited with ${r.status}`);
  process.exit(r.status ?? 1);
}
console.log('wrote', pyOut);
